"""Write artifact/MANIFEST.md: every macro used by the manuscript, its value, and the
script and saved result file that produce it.

Classification is by macro family:
  R1  -> results/tables/round1_confirm.json   (artifact/code/round1_confirm.py)
  DIAG-> results/tables/diag_*.json           (artifact/code/diag_index_vs_myopic.py, diag_redundancy.py)
  LAT -> results/judge_latency.json           (artifact/code/judge_latency.py)
  INV -> results/tables/inventory.json        (artifact/code/inventory_runs.py)
  R0  -> manuscript/numbers.tex               (artifact/code/analyze.py, from results/runs, results/tables,
                                               data/models*, data/graph/stats.json, results/gain_curve*.json)
"""
import os
import re

from manifest_evidence import auc_section

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.dirname(HERE)
MS = os.path.join(ART, "..", "manuscript")

R1_PREFIX = ("RT", "RZ", "PTwo", "DeltaTOST", "CalHardPct", "ValHardPct", "TestHardPct")
R1_EXACT = {"JudgeSecPerCall", "FetchSecPtOne"}
DIAG_EXACT = {"GateCommitDepthThree", "LinksSeen", "GateNLinks", "NGraphLinks"}


def macros(path):
    out = {}
    for line in open(path):
        m = re.match(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}\s*$", line)
        if m:
            out[m.group(1)] = m.group(2)
    return out


def used():
    files = [os.path.join(MS, "main.tex")] + sorted(
        os.path.join(MS, "sections", f) for f in os.listdir(os.path.join(MS, "sections")) if f.endswith(".tex"))
    u = {}
    for f in files:
        for m in re.finditer(r"\\([A-Za-z]+)", open(f).read()):
            u.setdefault(m.group(1), set()).add(os.path.basename(f))
    return u


def origin(name):
    if name in DIAG_EXACT:
        return "DIAG"
    if name in R1_EXACT or name.startswith(R1_PREFIX):
        return "R1"
    return "R0"


def main():
    vals = macros(os.path.join(MS, "numbers_all.tex"))
    u = used()
    names = sorted(n for n in u if n in vals)
    rows = []
    for n in names:
        o = origin(n)
        src = {
            "R1": "results/tables/round1_confirm.json",
            "DIAG": "results/tables/diag_index.json, diag_redundancy.json",
            "R0": "results/runs + results/tables + data/models* + results/gain_curve*.json",
        }[o]
        script = {
            "R1": "code/round1_confirm.py -> code/make_numbers_and_table.py",
            "DIAG": "code/diag_index_vs_myopic.py, code/diag_redundancy.py -> code/make_numbers_and_table.py",
            "R0": "code/analyze.py",
        }[o]
        rows.append((n, o, vals[n], script, src))
    missing = sorted(n for n in u if n not in vals and n[0].isupper() and n not in
                     {"Policy", "Recall", "Calls", "TOST", "Band", "Top", "Thompson", "Scorer", "TwoCost", "TT"})
    with open(os.path.join(ART, "MANIFEST.md"), "w") as f:
        f.write("# Artifact manifest: paper macro -> script -> saved result\n\n")
        f.write("Regeneration order (all read-only with respect to saved runs, logs and frozen hashes):\n\n")
        f.write("1. `../.venv-wsl/bin/python code/analyze.py` -> `manuscript/numbers.tex` (round-0 numbers, from saved runs/models)\n")
        f.write("2. `../.venv-wsl/bin/python code/round1_confirm.py` -> `results/tables/round1_confirm.json` (confirmatory analysis, blocks 80-200)\n")
        f.write("3. `../.venv-wsl/bin/python code/inventory_runs.py` -> `results/tables/inventory.json` (per-cell crawl inventory)\n")
        f.write("4. `../.venv-wsl/bin/python code/make_numbers_and_table.py` -> `manuscript/numbers_all.tex`, `manuscript/sections/tab_r1.tex`\n")
        f.write("5. `../.venv-wsl/bin/python code/verify_table.py` -> checks every number in `tab_r1.tex` against `round1_confirm.json`\n")
        f.write("6. `cd manuscript && latexmk -pdf main.tex` -> `manuscript/main.pdf`\n\n")
        f.write("`main.tex` inputs exactly one numbers file, `numbers_all.tex`. `numbers.tex` (round 0) and\n")
        f.write("`numbers_r1.tex` (stale, superseded) are kept for provenance and are not input.\n\n")
        f.write("| macro | value | origin | producing script | saved result |\n|---|---|---|---|---|\n")
        for n, o, v, s, src in rows:
            v = v.replace("|", "\\|")
            f.write(f"| `\\{n}` | {v} | {o} | {s} | {src} |\n")
        f.write("\nTable `tab:main` is generated by `code/make_numbers_and_table.py` from the same\n")
        f.write("`results/tables/round1_confirm.json`; its cells are the macros above with the `RT`/`RZ` prefixes.\n")
        if missing:
            f.write("\nUsed but not defined in numbers_all.tex: " + ", ".join(missing) + "\n")
        f.write(auc_section())
    print(f"wrote {os.path.join(ART, 'MANIFEST.md')} with {len(rows)} macros; undefined used: {missing}")


if __name__ == "__main__":
    main()
