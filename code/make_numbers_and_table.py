"""Build the single active numbers file and the confirmatory table from saved results.

Inputs (read-only):
  manuscript/numbers.tex                     round-0 macros, regenerated by artifact/code/analyze.py
  results/tables/round1_confirm.json         confirmatory analysis on blocks 80-200
  results/judge_latency.json                 judge throughput
  results/tables/inventory.json              per-cell crawl inventory
Outputs:
  manuscript/numbers_all.tex                 the only numbers file main.tex inputs
  manuscript/sections/tab_r1.tex             the confirmatory table

Every macro value is copied from a file listed above; nothing is typed by hand.
Run from artifact/code:  ../.venv-wsl/bin/python make_numbers_and_table.py
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.dirname(HERE)
MS = os.path.join(ART, "..", "manuscript")
R = os.path.join(ART, "results")

DELTA = 0.02
RW = {"0.1": "PtOne", "1": "One"}
PN = {"ours": "Ours", "topm": "Topm", "thompson": "TS", "band": "Band"}
REG = (("trained", "RT"), ("zeroshot", "RZ"))


def fmt(x, d=3):
    return f"{x:.{d}f}"


def sgn(x, d=3):
    if abs(x) < 5e-4:
        x = 0.0
    return f"{x:+.{d}f}"


def ci(t, d=3):
    return f"{sgn(t['mean'], d)} [{sgn(t['lo95'], d)}, {sgn(t['hi95'], d)}]"


def pval(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def read_base():
    macros = {}
    for line in open(os.path.join(MS, "numbers.tex")):
        m = re.match(r"\\newcommand\{\\([A-Za-z]+)\}\{(.*)\}\s*$", line)
        if m:
            macros[m.group(1)] = m.group(2)
    return macros


def main():
    base = read_base()
    conf = json.load(open(os.path.join(R, "tables", "round1_confirm.json")))
    inv = json.load(open(os.path.join(R, "tables", "inventory.json")))
    di = json.load(open(os.path.join(R, "tables", "diag_index.json")))
    dr = json.load(open(os.path.join(R, "tables", "diag_redundancy.json")))
    lat = json.load(open(os.path.join(R, "judge_latency.json")))

    num = dict(base)
    num["DeltaTOST"] = fmt(DELTA, 2)
    num["JudgeSecPerCall"] = fmt(lat["seconds_per_call_at_median_throughput"], 2)
    num["FetchSecPtOne"] = fmt(10 * lat["seconds_per_call_at_median_throughput"], 1)

    cells = conf["cells"]
    for reg, T in REG:
        for rho, K in RW.items():
            c = cells[reg][rho]
            num[f"{T}N{K}"] = str(c["n"])
            num[f"{T}NQ{K}"] = str(c["nq"])
            num[f"{T}Scorer{K}"] = fmt(c["scorer"]["recall"])
            for p, P in PN.items():
                v = c[p]
                d = v["vs_scorer"]
                num[f"{T}{P}{K}"] = fmt(v["recall"])
                num[f"{T}{P}Calls{K}"] = fmt(v["calls"], 1)
                num[f"{T}{P}DiffCrawls{K}"] = str(v["diff_crawls"])
                num[f"{T}{P}D{K}"] = ci(d)
                num[f"{T}{P}DPoint{K}"] = sgn(d["mean"])
                num[f"{T}{P}Eq{K}"] = "yes" if d["equiv"] else "no"
                num[f"{T}{P}Tost{K}"] = "eq" if d["equiv"] else ("below" if d["hi95"] < -DELTA else "n.s.")
                num[f"{T}{P}PHolm{K}"] = pval(d["p_holm"])
                num[f"{T}{P}PHolmRaw{K}"] = pval(d["p"])
                if "ours_minus" in v:
                    o = v["ours_minus"]
                    num[f"{T}OursMinus{P}{K}"] = ci(o)
                    num[f"{T}OursMinus{P}DPoint{K}"] = sgn(o["mean"])
                    num[f"{T}OursMinus{P}Tost{K}"] = "eq" if o["equiv"] else ("above" if o["lo95"] > DELTA else ("below" if o["hi95"] < -DELTA else "n.s."))
                    num[f"{T}OursMinus{P}PHolm{K}"] = pval(o["p_holm"])
                    num[f"{T}OursMinus{P}PHolmRaw{K}"] = pval(o["p"])
            num[f"{T}WorstHeurD{K}"] = sgn(min(c[p]["vs_scorer"]["mean"] for p in ("band", "topm", "thompson")))
            num[f"{T}WorstHeurWho{K}"] = min(("band", "topm", "thompson"), key=lambda p: c[p]["vs_scorer"]["mean"]).capitalize()

    p2 = conf["prediction2"]["confirm_80_200"]
    for d, w in ((2, "Two"), (3, "Three"), (4, "Four")):
        num[f"PTwoSameD{w}"] = ci(p2["greedy"][str(d)])
        num[f"PTwoBinD{w}"] = ci(p2["greedy_bin"][str(d)])
    num["PTwoSameAll"] = ci(p2["greedy"]["all"])
    num["PTwoSameAllEq"] = "yes" if p2["greedy"]["all"]["equiv"] else "no"
    wide = conf["prediction2"]["wide_80_400"]["greedy"]
    num["PTwoWideDThree"] = ci(wide["3"])
    num["PTwoWideDAll"] = ci(wide["all"])
    num["PTwoBinDThreeSig"] = "yes" if p2["greedy_bin"]["3"]["lo95"] > 0 else "no"
    num["PTwoDThree"] = ci(p2["greedy"]["3"])
    num["PTwoN"] = str(p2["greedy"]["all"]["n"])
    num["PTwoNQ"] = str(p2["greedy"]["all"]["nq"])
    num["GateCommitDepthThree"] = f"{100 * di['frac_links_commit_depth']['3']:.0f}\\%"
    num["LinksSeen"] = f"{dr['index_T']['mean_links_seen']:.0f}"
    num["GateNLinks"] = f"{di['gateway_links']['n']:,}".replace(",", "{,}")
    num["NGraphLinks"] = f"{di['n_links']:,}".replace(",", "{,}")
    # difficulty split, from the confirmatory analysis (levels)
    lv = conf["levels"]

    def hard_pct(split):
        d = lv[split]
        return f"{100 * d['hard'] / sum(d.values()):.0f}\\%"

    num["CalHardPct"] = hard_pct("cal")
    num["ValHardPct"] = hard_pct("val")
    num["TestHardPct"] = hard_pct("test")


    # ---------------- table
    NAME = {"ours": "\\system", "band": "Band cascade", "topm": "Top-$m$ + uncertainty", "thompson": "Thompson over links"}
    lines = []
    lines.append("\\begin{tabular}{@{}l@{\\hspace{2pt}}ccccc@{\\hspace{6pt}}ccc@{}}\\toprule")
    lines.append(" & \\multicolumn{5}{c}{$\\rho=0.1$ (primary)} & \\multicolumn{3}{c}{$\\rho=1$}\\\\")
    lines.append("\\cmidrule(lr){2-6}\\cmidrule(l){7-9}")
    lines.append("Policy & Recall & $\\Delta$ [95\\% CI] & $p_{\\mathrm{Holm}}$ & Calls & TOST & $\\Delta$ [95\\% CI] & Calls & TOST\\\\\\midrule")
    for reg, T in REG:
        c1, c2 = cells[reg]["0.1"], cells[reg]["1"]
        head = "trained scorer" if reg == "trained" else "zero-shot scorer"
        lines.append(f"\\multicolumn{{9}}{{@{{}}l}}{{\\emph{{{head}: {c1['nq']} questions, {c1['n']} crawls per cell}}}}\\\\")
        lines.append(f"Scorer alone & {fmt(c1['scorer']['recall'])} & & & 0 & & & 0 & \\\\")
        for p in ("ours", "band", "topm", "thompson"):
            v, w = c1[p], c2[p]
            eq = "$^{\\equiv}$" if v["vs_scorer"]["equiv"] else ""
            nm = f"\\textbf{{{NAME[p]}}}" if p == "ours" else NAME[p]
            lines.append(f"{nm} & {fmt(v['recall'])} & {ci(v['vs_scorer'])} & {pval(v['vs_scorer']['p_holm'])} & "
                         f"{fmt(v['calls'], 1)} & {'eq' if v['vs_scorer']['equiv'] else '--'} & "
                         f"{ci(w['vs_scorer'])} & {fmt(w['calls'], 1)} & {'eq' if w['vs_scorer']['equiv'] else '--'}\\\\")
        if reg == "trained":
            lines.append("\\midrule")
    lines.append("\\bottomrule\\end{tabular}")
    os.makedirs(os.path.join(MS, "sections"), exist_ok=True)
    with open(os.path.join(MS, "sections", "tab_r1.tex"), "w") as f:
        f.write("\n".join(lines) + "\n")

    with open(os.path.join(MS, "numbers_all.tex"), "w") as f:
        f.write("% generated by artifact/code/make_numbers_and_table.py from\n")
        f.write("%   manuscript/numbers.tex (round-0, from analyze.py), results/tables/round1_confirm.json,\n")
        f.write("%   results/tables/inventory.json, results/judge_latency.json\n")
        for k in sorted(num):
            f.write(f"\\newcommand{{\\{k}}}{{{num[k]}}}\n")
    print(f"wrote {os.path.join(MS, 'numbers_all.tex')} ({len(num)} macros)")
    print(f"wrote {os.path.join(MS, 'sections', 'tab_r1.tex')}")
    print(open(os.path.join(MS, "sections", "tab_r1.tex")).read())


if __name__ == "__main__":
    main()
